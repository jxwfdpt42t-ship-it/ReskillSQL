from __future__ import annotations

from collections import defaultdict
from dataclasses import dataclass
from typing import Any


@dataclass(frozen=True)
class PatchBundle:
    candidate_patches: list[dict[str, Any]]
    aggregated_patches: list[dict[str, Any]]
    markdown: str


class SQLAwarePatchAggregator:
    """Merge candidate patches by SQL error category without dropping evidence."""

    def aggregate(self, candidate_patches: list[dict[str, Any]]) -> list[dict[str, Any]]:
        grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
        for idx, patch in enumerate(candidate_patches, 1):
            category = str(patch.get("category") or "other_sql_error").strip() or "other_sql_error"
            normalized = dict(patch)
            normalized.setdefault("patch_id", f"{category}_candidate_{idx:03d}")
            normalized["category"] = category
            grouped[category].append(normalized)

        aggregated = []
        for idx, (category, patches) in enumerate(
            sorted(grouped.items(), key=lambda item: (-len(item[1]), item[0])),
            1,
        ):
            support_examples = _dedupe_flat(patch.get("support_examples", []) for patch in patches)
            detector_evidence = _dedupe_flat(patch.get("detector_evidence", []) for patch in patches)
            contrastive_signals = _dedupe_flat(patch.get("contrastive_signals", []) for patch in patches)
            workflow_steps = _dedupe_flat(patch.get("workflow_steps", []) for patch in patches)
            mandatory_pre_sql_plan = _first_plan(patches)
            wrong_behaviors = _dedupe(str(patch.get("wrong_behavior") or "").strip() for patch in patches)
            replacement_behaviors = _dedupe(str(patch.get("replacement_behavior") or "").strip() for patch in patches)
            rule_texts = _dedupe(str(patch.get("rule_text") or patch.get("rule") or "").strip() for patch in patches)
            aggregated.append(
                {
                    "patch_id": f"{category}_aggregated_{idx:03d}",
                    "category": category,
                    "merged_from": [str(patch.get("patch_id")) for patch in patches],
                    "support_examples": support_examples,
                    "detector_evidence": detector_evidence,
                    "contrastive_signals": contrastive_signals,
                    "workflow_steps": workflow_steps[:6],
                    "mandatory_pre_sql_plan": mandatory_pre_sql_plan,
                    "wrong_behavior": _merge_rule_texts(wrong_behaviors),
                    "replacement_behavior": _merge_rule_texts(replacement_behaviors),
                    "rule_text": _merge_rule_texts(rule_texts),
                    "information_preserved": {
                        "num_candidate_patches": len(patches),
                        "num_support_examples": len(support_examples),
                        "num_detector_evidence": len(detector_evidence),
                        "num_contrastive_signals": len(contrastive_signals),
                        "num_workflow_steps": len(workflow_steps),
                    },
                }
            )
        return aggregated

    def render_markdown(self, aggregated_patches: list[dict[str, Any]]) -> str:
        lines = [
            "## Learned Rules From Validation Failures",
            "",
            "These rules were generated by the optimizer LLM, aggregated by SQL error category, and grounded in execution evidence.",
        ]
        for patch in aggregated_patches:
            category = str(patch.get("category") or "other_sql_error")
            rule_text = str(patch.get("rule_text") or "").strip()
            if not rule_text:
                continue
            lines.append(f"- **{category}**: {rule_text}")
            if patch.get("wrong_behavior"):
                lines.append(f"  - Wrong behavior: {patch['wrong_behavior']}")
            if patch.get("replacement_behavior"):
                lines.append(f"  - Replacement behavior: {patch['replacement_behavior']}")
            plan = patch.get("mandatory_pre_sql_plan") or {}
            if plan.get("title"):
                lines.append(f"  - Mandatory plan: {plan['title']}")
                for index, step in enumerate((plan.get("steps") or [])[:4], 1):
                    lines.append(f"    {index}. {step}")
            workflow_steps = patch.get("workflow_steps") or []
            for index, step in enumerate(workflow_steps[:4], 1):
                lines.append(f"  - Workflow {index}: {step}")
            evidence = patch.get("detector_evidence") or []
            for item in evidence[:3]:
                lines.append(f"  - Evidence: {item}")
            if patch.get("merged_from"):
                lines.append(f"  - Merged from: {', '.join(patch['merged_from'])}")
        return "\n".join(lines).strip() + "\n"

    def build_bundle(self, candidate_patches: list[dict[str, Any]]) -> PatchBundle:
        aggregated = self.aggregate(candidate_patches)
        markdown = self.render_markdown(aggregated)
        return PatchBundle(candidate_patches, aggregated, markdown)


def _dedupe(values) -> list[str]:
    seen = []
    for value in values:
        if not value:
            continue
        if value not in seen:
            seen.append(value)
    return seen


def _dedupe_flat(groups) -> list[str]:
    values = []
    for group in groups:
        if isinstance(group, list):
            values.extend(str(item) for item in group if item)
        elif group:
            values.append(str(group))
    return _dedupe(values)


def _merge_rule_texts(rule_texts: list[str]) -> str:
    if not rule_texts:
        return ""
    if len(rule_texts) == 1:
        return rule_texts[0]
    # Keep the most comprehensive rule first, then preserve non-duplicate sub-rules.
    ordered = sorted(rule_texts, key=len, reverse=True)
    base = ordered[0].rstrip(".")
    additions = [text.rstrip(".") for text in ordered[1:] if text.rstrip(".").lower() not in base.lower()]
    if not additions:
        return base + "."
    return base + "; also consider: " + "; ".join(additions) + "."


def _first_plan(patches: list[dict[str, Any]]) -> dict[str, Any]:
    for patch in patches:
        plan = patch.get("mandatory_pre_sql_plan")
        if isinstance(plan, dict) and plan.get("title") and isinstance(plan.get("steps"), list):
            return {
                "title": str(plan["title"]),
                "steps": [str(step) for step in plan["steps"] if str(step).strip()][:4],
            }
    return {}
